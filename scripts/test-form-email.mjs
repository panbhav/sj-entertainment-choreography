import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const source = await readFile('src/lib/form-email.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { sendFormEmail, formEmailEndpoint } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const calls = [];
const accepted = async (url, options) => { calls.push({ url, options }); return Response.json({ success: 'true' }); };
assert.equal((await sendFormEmail('enquiry', { Name: 'Test', Services: 'Couple dance, Cousins Dance', email: 'test@example.com', _subject: 'injected', _cc: 'wrong@example.com' }, '', accepted)).success, true);
const enquiry = JSON.parse(calls[0].options.body);
assert.equal(calls[0].url, formEmailEndpoint);
assert.equal(enquiry._subject, 'SJ Website — New celebration enquiry');
assert.equal(enquiry._cc, undefined);
assert.equal(enquiry.Services, 'Couple dance, Cousins Dance');
assert.equal(enquiry.email, 'test@example.com');
assert.equal(enquiry._captcha, undefined);
assert.ok(calls[0].options.signal);
assert.equal((await sendFormEmail('team', { Skills: 'Test skills', Portfolio: 'https://example.com/work' }, '', accepted)).success, true);
assert.equal(JSON.parse(calls[1].options.body)._subject, 'SJ Website — New team introduction');
const activation = await sendFormEmail('enquiry', {}, '', async () => Response.json({ success: 'false', message: 'This form needs Activation' }));
assert.equal(activation.success, false);
assert.match(activation.message, /awaiting activation/);
assert.equal((await sendFormEmail('team', {}, '', async () => Response.json({ success: false }))).success, false);
assert.equal((await sendFormEmail('team', {}, '', async () => Response.json({ success: 'true' }, { status: 429 }))).success, false);
let spamCalls = 0;
assert.equal((await sendFormEmail('team', {}, 'spam', async () => { spamCalls++; return Response.json({ success: true }); })).success, false);
assert.equal(spamCalls, 0);
await assert.rejects(sendFormEmail('enquiry', {}, '', async () => { throw new Error('Network unavailable'); }));
await assert.rejects(sendFormEmail('enquiry', {}, '', async () => new Response('not JSON')));
console.log('FormSubmit mocked checks passed: payloads, fixed endpoint, subject isolation, activation/string booleans, HTTP errors, spam trap and transport failures. No external requests sent.');
